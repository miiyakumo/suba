/// 任务状态枚举
///
/// ## 状态机转换
/// ```text
///     ┌──────┐
///     │ Ready │ ←── 新任务创建
///     └──┬───┘
///        │ 被调度器选中
///        ▼
///     ┌──────┐
///     │Running│
///     └──┬───┘
///        │
///   ┌────┼────┐
///   │    │    │
///   ▼    │    ▼
/// ┌───┐  │  ┌─────┐
/// │Wait│  │  │Exited│
/// └─┬─┘  │  └─────┘
///   │    │
///   └────┘→ 回到 Ready
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TaskState {
    /// 就绪态：等待被调度
    Ready,
    /// 运行态：正在 CPU 上执行
    Running,
    /// 等待态：等待某个事件（如 I/O 完成）
    Waiting,
    /// 退出态：任务已结束
    Exited,
}
