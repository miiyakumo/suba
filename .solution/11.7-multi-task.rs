// Solution: 11.7 — 多任务调度验证
//
// 本文件展示抢占式多任务调度的完整实现。
//
// ============================================================================
// 核心架构
// ============================================================================
//
// 1. 每个任务有独立的 TrapFrame（存储在 TRAP_FRAMES 全局映射中）
// 2. 时钟中断触发 schedule_next()，设置 NEXT_TRAP_FRAME
// 3. trap_entry 在 trap_handler 返回后检查 NEXT_TRAP_FRAME
// 4. 若有待切换任务，从新 TrapFrame 恢复寄存器并 sret
//
// ============================================================================
// 关键数据结构
// ============================================================================
//
// static TRAP_FRAMES: spin::Once<spin::Mutex<BTreeMap<usize, Box<TrapFrame>>>>;
//
// #[no_mangle]
// pub static NEXT_TRAP_FRAME: AtomicPtr<TrapFrame>;
//
// ============================================================================
// schedule_next() 实现
// ============================================================================
//
// fn schedule_next(current_tf: *mut TrapFrame) {
//     // 1. 保存当前任务的 TrapFrame
//     // 2. 将当前任务放回调度队列
//     // 3. 从调度器获取下一个任务
//     // 4. 设置 NEXT_TRAP_FRAME
// }
//
// ============================================================================
// trap.S 中的上下文切换
// ============================================================================
//
// trap_entry:
//     call trap_handler
//     la t0, NEXT_TRAP_FRAME
//     ld t1, 0(t0)
//     beqz t1, .Lrestore_and_sret
//     sd zero, 0(t0)
//     mv a0, t1
// .Lrestore_and_sret:
//     # 恢复寄存器并 sret
//
// ============================================================================
// 教学要点
// ============================================================================
//
// 1. 抢占式调度：时钟中断强制切换任务
// 2. TrapFrame 保存/恢复：每个任务的完整寄存器状态独立存储
// 3. 原子变量 NEXT_TRAP_FRAME：无锁通信机制
// 4. trap.S 中的上下文切换：汇编级实现
// 5. 中断安全锁：禁用中断防止死锁
