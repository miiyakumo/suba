/// SpinLock 类型别名。
///
/// ## 教学概念
/// 内核中不能使用标准库的 `std::sync::Mutex`（它会阻塞线程），
/// 而是使用**自旋锁 (SpinLock)**：当锁被持有时，CPU 不断循环检查
/// （"自旋"），直到锁可用。
///
/// 为什么不用互斥锁？
/// - 内核中没有"线程调度器"来唤醒被阻塞的线程
/// - 自旋锁简单、确定性强，适合短临界区
/// - 在中断上下文中，自旋锁是唯一安全的同步方式
///
/// 使用 `spin` crate 提供的 `spin::Mutex`，它是 `no_std` 兼容的。
pub type SpinLock<T> = spin::Mutex<T>;
